const MCC_DESCRIPTION_RANGES: Array<{ from: number; to: number; description: string }> = [
  { from: 3000, to: 3299, description: "Путешествия" },
  { from: 3300, to: 3499, description: "Путешествия" },
  { from: 3500, to: 3999, description: "Путешествия" },
];

/**
 * Возвращает расшифровку по коду MCC или null, если неизвестен.
 */
export function getMccDescription(code: string): string | null {
  const raw = String(code ?? "").trim();
  if (!raw) return null;
  const digits = raw.replace(/\D/g, "");
  if (!digits) return null;
  const direct = MCC_DESCRIPTION_BY_CODE[digits];
  if (direct) return direct;
  const num = Number(digits);
  if (!Number.isFinite(num)) return null;
  const range = MCC_DESCRIPTION_RANGES.find((r) => num >= r.from && num <= r.to);
  return range ? range.description : null;
}

/**
 * Для маппинга категорий при импорте: если rawCategory — это код MCC (цифры),
 * возвращает «код — расшифровка», иначе исходную строку.
 */
export function formatMccCategoryForImport(rawCategory: string): string {
  const trimmed = rawCategory.trim();
  if (!trimmed) return trimmed;
  const digits = trimmed.replace(/\D/g, "");
  if (digits.length < 4) return trimmed;
  const code = digits.length <= 4 ? digits : digits.slice(0, 4);
  const description = getMccDescription(code);
  if (!description) return trimmed;
  return `${code} — ${description}`;
}
