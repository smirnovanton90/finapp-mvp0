"""
Рабочие дни по ТК РФ: выходные (сб/вс), нерабочие праздничные дни (ст. 112 ТК РФ)
и перенесённые Правительством РФ выходные.
Используется для переноса даты платежа на первый следующий рабочий день.
"""

from datetime import date, timedelta

# Нерабочие праздничные дни по ст. 112 ТК РФ (month, day)
FIXED_HOLIDAYS: list[tuple[int, int]] = [
    (1, 1), (1, 2), (1, 3), (1, 4), (1, 5), (1, 6), (1, 7), (1, 8),  # Новогодние каникулы и Рождество
    (2, 23),   # День защитника Отечества
    (3, 8),    # Международный женский день
    (5, 1),    # Праздник Весны и Труда
    (5, 9),    # День Победы
    (6, 12),   # День России
    (11, 4),   # День народного единства
]

# Перенесённые выходные (дата становится нерабочей). Постановления Правительства РФ.
TRANSFERRED_DAYS: frozenset[date] = frozenset({
    date(2024, 12, 31),  # с 5 янв 2025
    date(2025, 5, 2),    # с 4 янв 2025
    date(2025, 5, 8),    # с 23 фев 2025
    date(2025, 6, 13),   # с 8 мар 2025
    date(2025, 11, 3),   # с 1 ноя 2025
    date(2025, 12, 31),  # с 4 янв 2026
    date(2026, 1, 9),    # с 3 янв 2026
    date(2027, 2, 9),    # с 8 мар 2027
    date(2027, 5, 31),   # с 1 янв 2027
})


def is_non_working_day(d: date) -> bool:
    """Является ли дата нерабочей (суббота, воскресенье, праздник или перенесённый день)."""
    w = d.weekday()  # Monday=0, Sunday=6
    if w >= 5:
        return True
    for (m, day) in FIXED_HOLIDAYS:
        if d.month == m and d.day == day:
            return True
    if d in TRANSFERRED_DAYS:
        return True
    return False


def get_next_workday(d: date) -> date:
    """Возвращает первый рабочий день начиная с данной даты (включительно)."""
    while is_non_working_day(d):
        d += timedelta(days=1)
    return d
